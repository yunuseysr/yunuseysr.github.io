#!/usr/bin/env python3
"""Rebuild js/icons.js — the Font Awesome 5 Free icons this site actually uses, as inline SVG.

The site used to load Font Awesome's 1.2 MB all.js. icons.js carries only the icons referenced as
`fas|fab|far fa-NAME` in the HTML / JS files and swaps <i> tags for <svg> the same way all.js did, so the
markup and CSS stay the same. Run it again after using a new icon:

    python3 scripts/build-icons.py            # downloads Font Awesome 5.15.4 all.js
    python3 scripts/build-icons.py all.js     # or use a local copy
"""
import json
import re
import sys
import urllib.request
from pathlib import Path

FA_URL = "https://use.fontawesome.com/releases/v5.15.4/js/all.js"
ROOT = Path(__file__).resolve().parent.parent
SCAN = ["*.html", "tr/*.html", "tools/**/*.html", "tools/*.js", "notes/**/*.html", "js/*.js"]
OUT = ROOT / "js" / "icons.js"

ENTRY = re.compile(r'(?:"([a-z0-9-]+)"|([a-z0-9_$]+)):\[(\d+),(\d+),\[[^\]]*\],"[0-9a-f]+","([^"]+)"\]')


def fa_icons(src: str) -> dict:
    """{'fas': {name: (w, h, path)}, ...}. all.js defines one object per style, closed by M("fab"|"far"|"fas", f)."""
    icons, start = {}, 0
    for m in re.finditer(r'M\("(fab|far|fas)",f\)', src):
        block = src[start:m.start()]
        icons[m.group(1)] = {(e.group(1) or e.group(2)): (int(e.group(3)), int(e.group(4)), e.group(5))
                             for e in ENTRY.finditer(block)}
        start = m.end()
    return icons


def used_icons() -> set:
    found = set()
    for pattern in SCAN:
        for f in ROOT.glob(pattern):
            if f == OUT:
                continue
            found |= set(re.findall(r"\b(fas|fab|far) fa-([a-z0-9-]+)", f.read_text(encoding="utf-8")))
    return found


def main():
    if len(sys.argv) > 1:  # a local copy of all.js
        src = Path(sys.argv[1]).read_text(encoding="utf-8")
    else:
        req = urllib.request.Request(FA_URL, headers={"User-Agent": "Mozilla/5.0 (build-icons script)"})
        src = urllib.request.urlopen(req, timeout=60).read().decode("utf-8")
    icons = fa_icons(src)
    table, missing = {}, []
    for prefix, name in sorted(used_icons()):
        hit = icons.get(prefix, {}).get(name)
        if hit:
            table[f"{prefix} {name}"] = list(hit)
        else:
            missing.append(f"{prefix} fa-{name}")
    OUT.write_text(TEMPLATE.replace("__ICONS__", json.dumps(table, separators=(",", ":"))), encoding="utf-8")
    print(f"{OUT.relative_to(ROOT)}: {len(table)} icons, {OUT.stat().st_size // 1024} KB")
    if missing:
        print("not in Font Awesome 5 Free:", ", ".join(missing), file=sys.stderr)
        sys.exit(1)


TEMPLATE = """/*! Icons: Font Awesome Free 5.15.4 by @fontawesome - https://fontawesome.com
 *  License - https://fontawesome.com/license/free (Icons: CC BY 4.0)
 *  Generated by scripts/build-icons.py — only the icons this site uses. Do not edit by hand. */
(() => {
    'use strict';
    const ICONS = __ICONS__;
    const NS = 'http://www.w3.org/2000/svg';
    const SELECTOR = 'i.fas, i.fab, i.far';

    function swap(el) {
        const prefix = ['fas', 'fab', 'far'].find(p => el.classList.contains(p));
        const name = prefix && [...el.classList].find(c => c.startsWith('fa-') && ICONS[`${prefix} ${c.slice(3)}`]);
        if (!name) return;
        const [w, h, d] = ICONS[`${prefix} ${name.slice(3)}`];
        const svg = document.createElementNS(NS, 'svg');
        svg.setAttribute('class', `${el.getAttribute('class')} svg-inline--fa`);
        svg.setAttribute('viewBox', `0 0 ${w} ${h}`);
        svg.setAttribute('aria-hidden', 'true');
        svg.setAttribute('focusable', 'false');
        svg.setAttribute('style', `${el.getAttribute('style') || ''};width:${(w / h).toFixed(4)}em`);
        const path = document.createElementNS(NS, 'path');
        path.setAttribute('fill', 'currentColor');
        path.setAttribute('d', d);
        svg.appendChild(path);
        el.replaceWith(svg);
    }

    const scan = root => root.querySelectorAll && root.querySelectorAll(SELECTOR).forEach(swap);
    scan(document);
    new MutationObserver(records => records.forEach(r => r.addedNodes.forEach(n => {
        if (n.nodeType !== 1) return;
        if (n.matches(SELECTOR)) swap(n); else scan(n);
    }))).observe(document.documentElement, { childList: true, subtree: true });
})();
"""

if __name__ == "__main__":
    main()
